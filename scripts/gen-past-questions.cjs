// Generates src/data/pastQuestions.js by extracting the question banks straight
// out of the legacy "First Nexus" PastQuestions HTML files. Run with:
//   node scripts/gen-past-questions.cjs
//
// Keeping this as a generator (rather than hand-transcribing ~70 MCQs + essays)
// means the migrated data stays byte-faithful to the original papers.

const fs = require('fs');
const path = require('path');

const LEGACY = path.join(
  __dirname,
  '..',
  'Test Upload im trying to migrate',
  'First Nexus',
  'PastQuestions'
);

// Pull the `const <varName> = [ ... ]` array literal out of a source string,
// matching brackets while skipping over string/template contents so that any
// stray [ ] inside the question text can't throw the matcher off.
function extractArray(src, varName) {
  const marker = `const ${varName} = [`;
  const mi = src.indexOf(marker);
  if (mi === -1) throw new Error(`could not find "${varName}" array`);

  const start = src.indexOf('[', mi);
  let depth = 0;
  let inStr = null;
  let esc = false;
  let i = start;

  for (; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === inStr) inStr = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') { inStr = c; continue; }
    if (c === '[') depth++;
    else if (c === ']') {
      depth--;
      if (depth === 0) { i++; break; }
    }
  }
  return src.slice(start, i); // includes the outer [ ... ]
}

function evalArray(src, varName) {
  // The legacy literals use unquoted keys + JS strings - valid as an expression.
  return new Function(`return ${extractArray(src, varName)}`)();
}

const cosSrc = fs.readFileSync(path.join(LEGACY, 'Cos101', '20232024.html'), 'utf8');
const gesSrc = fs.readFileSync(path.join(LEGACY, 'Ges101', '20232024.html'), 'utf8');

// ── Objective (COS 101): {q, options, answer, explanation, detailed} ──────────
const cosQuestions = evalArray(cosSrc, 'questions').map((q) => ({
  q: q.q,
  options: q.options,
  answer: q.answer,
  explanation: q.explanation || '',
  detailed: q.detailed || '',
}));

// ── Theory (GES 101): reshape to the essay-test shape used by aiGrader ────────
const gesQuestions = evalArray(gesSrc, 'questions').map((q) => {
  const out = {
    section: q.section,
    type: 'essay',
    label: `Question ${q.id}${q.subsection ? q.subsection : ''}`,
    marks: q.marks,
  };
  if (q.scenario) out.scenario = q.scenario;
  out.text = q.text;
  out.modelAnswer = q.modelAnswer;
  return out;
});

const data = {
  cos101: {
    code: 'COS 101',
    title: 'Introduction to Computing Sciences',
    years: {
      '20232024': {
        session: '2023/2024',
        type: 'objective',
        pdfUrl: '/pastquestions/COS101-20232024.pdf',
        questions: cosQuestions,
      },
    },
  },
  ges101: {
    code: 'GES 101',
    title: 'Law, Man and Society',
    subject: 'university law (GES 101 - Law, Man and Society)',
    years: {
      '20232024': {
        session: '2023/2024',
        type: 'theory',
        pdfUrl: '/pastquestions/GES101-20232024.pdf',
        durationMins: 60,
        sections: [
          { id: 'A', label: 'Section A - Compulsory (answer both parts)', pick: 'all' },
          { id: 'B', label: 'Section B - Answer ONE question only', pick: 1 },
        ],
        questions: gesQuestions,
      },
    },
  },
};

const header = `// AUTO-GENERATED by scripts/gen-past-questions.cjs - do not edit by hand.
// Seeded from the legacy First Nexus PastQuestions HTML (COS 101 objective +
// GES 101 theory, 2023/2024). Regenerate with: node scripts/gen-past-questions.cjs
//
// Shape: pastQuestions[slug] = { code, title, [subject], years: { [yearSlug]: quiz } }
//   objective quiz -> { session, type:'objective', pdfUrl, questions:[{q,options,answer,explanation,detailed}] }
//   theory quiz    -> { session, type:'theory', pdfUrl, durationMins, sections, subject, questions:[essayItem] }

`;

const out = `${header}export const pastQuestions = ${JSON.stringify(data, null, 2)};\n`;

const dest = path.join(__dirname, '..', 'src', 'data', 'pastQuestions.js');
fs.writeFileSync(dest, out, 'utf8');

console.log(
  `Wrote ${dest}\n  COS 101 objective: ${cosQuestions.length} questions\n  GES 101 theory:    ${gesQuestions.length} questions`
);
